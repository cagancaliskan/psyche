    print(f"  readout (anti-circularity)  : winner-SET identity (node-set), NOT the scalar")
    print(f"  grading mode (determinism)  : REPLAY over the frozen, hashed telemetry trace")
    print(f"  telemetry trace SHA-256     : {trace_hash}")
    print(f"  real observed friction range: [{observed_min:.6f} .. {observed_max:.6f}]")
    print(f"  swept friction levels ({len(friction_levels)})  : "
          f"{[round(f, 5) for f in friction_levels]}")
