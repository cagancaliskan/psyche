# -- telemetry capture (the real-measured span; honest, not inflated) --
CAPTURE_SAMPLES = 240          # number of real telemetry intervals to record
CONTENDED_SPIN_S = 0.004       # busy-spin duration -> CPU-bound interval (low friction)
IDLE_SLEEP_S = 0.004           # os sleep duration -> wall>>cpu interval (high friction)
# Alternate contended/idle so the captured distribution spans a REAL low->high range.

