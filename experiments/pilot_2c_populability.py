def main() -> int:
    load_frozen = os.environ.get("LOAD_FROZEN", "") == "1"

    if load_frozen:
        if not os.path.exists(TRACE_PATH):
            print(f"  ERROR: LOAD_FROZEN=1 but no frozen trace at {TRACE_PATH}; "
                  f"run once without LOAD_FROZEN to capture+freeze it first.")
            return 2
        samples, trace_hash = load_frozen_trace()
        print(f"  [LOAD_FROZEN] grading the already-frozen trace ({len(samples)} samples).")
    else:
        samples = capture_real_telemetry()
        trace_hash = save_and_hash_trace(samples)
        print(f"  [CAPTURE] recorded {len(samples)} real telemetry samples; "
              f"froze to {os.path.relpath(TRACE_PATH, _HERE)}.")

    frictions = frictions_from_trace(samples)
    if not frictions:
        print("  ERROR: the captured trace produced no friction values.")
        return 2
    observed_min, observed_max = min(frictions), max(frictions)
    friction_levels = sweep_levels_from_frictions(frictions, SWEEP_LEVELS)

    print_preregistration(trace_hash, friction_levels, observed_min, observed_max)

    # honesty check on the captured range: a degenerate (single-value) range cannot
    # populate the bar; report it plainly rather than masking it.
    if observed_max <= observed_min:
        print("\n  NOT-YET (degenerate capture): the real telemetry friction range collapsed "
              "to a single value on this machine/run — the sweep cannot exercise a span. This "
              "is an honest instrument/environment finding, NOT a loosening of the floor.")
        print(f"  observed friction (constant): {observed_min:.6f}")
        return 0

    battery = build_battery(BATTERY_SEED, PERCEPT_COUNT)

    print("\n  PER-PERCEPT FLIP RESULTS (winner-set distinct count across the swept range):")
    n_flip = 0
    n_with_winner = 0
    rows = []
    for label, builder, percept_text, _a, _b in battery:
        flips, n_distinct, has_winner = percept_flips(builder, percept_text, friction_levels)
        if has_winner:
            n_with_winner += 1
        if flips:
            n_flip += 1
        rows.append((label, flips, n_distinct, has_winner))
        print(f"    {label:38s}  winners={n_distinct}  flip={'YES' if flips else 'no '}"
              f"  {'(no winner)' if not has_winner else ''}")

    denom = n_with_winner if n_with_winner > 0 else len(battery)
    fraction = n_flip / denom if denom > 0 else 0.0

    print("\n" + "=" * 78)
    print("  2c POPULABILITY PILOT — RESULT (computed from the frozen replay, not hard-coded)")
    print("=" * 78)
    print(f"  percepts with a winner        : {n_with_winner} / {len(battery)}")
    print(f"  percepts that FLIPPED         : {n_flip}")
    print(f"  populability fraction         : {fraction:.4f}  ({fraction:.1%})")
    print(f"  pre-registered floor          : {POPULABILITY_FLOOR:.4f}  ({POPULABILITY_FLOOR:.0%})")
    print(f"  telemetry trace SHA-256       : {trace_hash}")
    print(f"  real observed friction range  : [{observed_min:.6f} .. {observed_max:.6f}]")
    if fraction >= POPULABILITY_FLOOR:
        print(f"\n  VERDICT: GO — {fraction:.1%} >= {POPULABILITY_FLOOR:.0%}. The loop's emergent")
        print("    selection IS moved by real telemetry across its observed range for at least")
        print("    the pre-registered fraction of percepts. STOP HERE: the validator's graded")
        print("    meaning run follows on the human's word. (This is NOT itself a meaning claim;")
        print("    it clears the populability gate so a meaning run is worth running.)")
    else:
        print(f"\n  VERDICT: NOT-YET — {fraction:.1%} < {POPULABILITY_FLOOR:.0%}. Honest finding:")
        print("    the loop is causally COUPLABLE in principle (the modulation is a real causal")
        print("    effect, proven in the mechanism suite) but real telemetry ranges do NOT move")
        print("    its emergent selection for enough percepts. The floor is NOT loosened, the")
        print("    range is NOT widened beyond what the machine produced, and nothing is")
        print("    redesigned to manufacture a pass. 2c stays DESIGNED; no brick is reopened.")
    print("=" * 78)
    return 0


