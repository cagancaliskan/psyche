# ══════════════════════════════════════════════════════════════════════════════
# 1) Telemetry capture (the ONE-TIME live boundary step; the only non-determinism)
# ══════════════════════════════════════════════════════════════════════════════

def _busy_spin(duration_s: float) -> None:
    """Burn CPU for ~duration_s of wall time (a genuinely CPU-bound interval -> wall~=cpu
    -> low friction). Pure stdlib; no sleep."""
    end = time.perf_counter() + duration_s
    x = 0
    while time.perf_counter() < end:
        x += 1  # keep the CPU busy
    return None


def capture_real_telemetry() -> list:
    """Capture a real telemetry trace as a list of TelemetrySample(perf, proc) pairs.

    Each recorded boundary read takes time.perf_counter() and time.process_time() at the
    same instant. Between reads we alternate a genuinely CPU-bound interval (busy-spin ->
    wall ~= cpu -> low friction) and a genuinely idle interval (os sleep -> wall >> cpu ->
    high friction), so the captured friction distribution spans a REAL low->high range. No
    value is hand-set or inflated; the friction is whatever the machine actually produced.
    """
    samples = []
    # prime: the very first read has no predecessor (BodySensor returns neutral for it)
    samples.append(TelemetrySample(perf=time.perf_counter(), proc=time.process_time()))
    for i in range(CAPTURE_SAMPLES):
        if i % 2 == 0:
            _busy_spin(CONTENDED_SPIN_S)        # CPU-bound -> low friction interval
        else:
            time.sleep(IDLE_SLEEP_S)            # idle/blocked -> high friction interval
        samples.append(TelemetrySample(perf=time.perf_counter(), proc=time.process_time()))
    return samples


def frictions_from_trace(samples: list) -> list:
    """Replay a frozen trace through a BodySensor and collect the friction value each read
    produces (skipping the first, which only primes the baseline). This is EXACTLY how the
    cycle would consume the trace — so the observed range is the cycle's real input range."""
    sensor = BodySensor(simulated=True, trace=samples)
    out = []
    for _ in range(len(samples)):
        try:
            out.append(sensor.read())
        except IndexError:
            break
    # drop the first (baseline / neutral) read
    return out[1:]


# ══════════════════════════════════════════════════════════════════════════════
# 2) Freeze + hash the trace (the frozen pre-registration artifact)
# ══════════════════════════════════════════════════════════════════════════════

def _trace_to_jsonable(samples: list) -> dict:
    return {
        "spec": "SPEC-2c populability pilot frozen telemetry trace",
        "capture_samples": CAPTURE_SAMPLES,
        "contended_spin_s": CONTENDED_SPIN_S,
        "idle_sleep_s": IDLE_SLEEP_S,
        "samples": [[s.perf, s.proc] for s in samples],
    }


def save_and_hash_trace(samples: list) -> str:
    os.makedirs(RESULTS_DIR, exist_ok=True)
    payload = _trace_to_jsonable(samples)
    # canonical, sorted JSON so the hash is a deterministic function of the trace content
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    digest = hashlib.sha256(blob).hexdigest()
    with open(TRACE_PATH, "w") as f:
        f.write(json.dumps(payload, sort_keys=True, indent=2))
    return digest


def load_frozen_trace() -> tuple:
    with open(TRACE_PATH, "r") as f:
        payload = json.load(f)
    samples = [TelemetrySample(perf=p, proc=q) for p, q in payload["samples"]]
    blob = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    digest = hashlib.sha256(blob).hexdigest()
    return samples, digest


