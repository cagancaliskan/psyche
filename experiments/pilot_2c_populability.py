# 3) Percept battery — randomized, fixed-seed, NOT hand-picked for flippability
# ══════════════════════════════════════════════════════════════════════════════

def _worn(s, a, b, n):
    for _ in range(n):
        s.traverse(a, b)


def build_battery(seed: int, count: int) -> list:
    """Generate `count` two-anchor topologies from a FIXED-SEED RNG. Each draws structural
    parameters from documented ranges; the battery is reproducible and NOT hand-selected to
    flip. Returns a list of (label, store_builder, percept_text, anchorA_content,
    anchorB_content). Content words are non-substring-overlapping so perception lights up
    exactly the two anchors.

    The structural lever is a CONTESTED NODE reached at different distances from the two
    anchors (the realistic flip mechanism: a node's basin allegiance crosses as decay_per_hop
    moves). Every percept is therefore movable IN PRINCIPLE; what the pilot MEASURES is
    whether the REAL telemetry range — replayed — actually contains each percept's crossover
    and thus moves its winner. That is exactly the SPEC-2c §1.4 populability question ("do
    real telemetry ranges move the emergent outcome enough"). Making the battery movable-in-
    principle keeps the number a clean measure of TELEMETRY-RANGE populability (not of
    structural unmovability for reasons unrelated to telemetry); the crossover positions are
    spread by bridge_n, set BEFORE any telemetry is seen, so this is not cherry-picking.

    Parameter space (per percept, drawn uniformly and INDEPENDENTLY of any outcome):
      - bridge_n   in [1..6]    : traversal-count (=> strength sA) of the MEDIUM alpha->mid
                                  road. This sets the crossover d* = sA / sB^2 (sB ~ 0.985);
                                  bridge_n in 1..6 spreads d* across ~[0.18 .. 0.60], so a
                                  percept flips iff the real swept decay range reaches its d*.
      - near_extra in [0..2]    : extra mirror near-neighbors on BOTH anchors (kept symmetric
                                  so they never themselves bias the winner) — pure structural
                                  diversity; does not by itself cause or prevent a flip.
    """
    rng = random.Random(seed)
    battery = []
    for i in range(count):
        bridge_n = rng.randint(1, 6)
        near_extra = rng.randint(0, 2)

        def make_builder(bridge_n=bridge_n, near_extra=near_extra):
            def builder():
                s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
                alpha = s.add_node("alpha", NodeType.CONCEPT)
                gamma = s.add_node("gamma", NodeType.CONCEPT)
                anode = s.add_node("anode", NodeType.CONCEPT)
                gnode = s.add_node("gnode", NodeType.CONCEPT)
                # mirror-symmetric tight neighbors (each anchor gets the same structure)
                _worn(s, alpha, anode, 30)
                _worn(s, gamma, gnode, 30)
                for k in range(near_extra):
                    ax = s.add_node(f"aextra{k}", NodeType.CONCEPT)
                    gx = s.add_node(f"gextra{k}", NodeType.CONCEPT)
                    _worn(s, alpha, ax, 30)
                    _worn(s, gamma, gx, 30)
                # the contested node: 1 medium hop from alpha, 2 strong hops from gamma.
                mid = s.add_node("midnode", NodeType.CONCEPT)  # a sink (no out-roads)
                _worn(s, alpha, mid, bridge_n)   # sets the crossover d* = sA/sB^2
                _worn(s, gnode, mid, 30)         # gamma -> gnode -> mid (the ~d^2 path)
                return s
            return builder

        label = f"p{i:02d}[bridge={bridge_n},nearextra={near_extra}]"
        battery.append((label, make_builder(), "alpha gamma", "alpha", "gamma"))
    return battery


# ══════════════════════════════════════════════════════════════════════════════
# 4) The sweep + flip metric (REPLAY grading; winner-SET readout)
# ══════════════════════════════════════════════════════════════════════════════

def sweep_levels_from_frictions(frictions: list, n_levels: int) -> list:
    """Pick n_levels friction values evenly spaced across the REAL observed min..max range
    (by quantile of the sorted observed frictions). Uses only the actual recorded span — no
    inflation beyond what the machine produced."""
    if not frictions:
        return []
    ordered = sorted(frictions)
    lo, hi = ordered[0], ordered[-1]
    if hi <= lo:
        return [lo]
    return [lo + (hi - lo) * (k / (n_levels - 1)) for k in range(n_levels)]


def _winner_set(s, r):
    """The winner readout: a frozenset of node CONTENTS (a node-SET), NOT the friction
    scalar — the anti-circularity ((C-GRADE-EMERGENT)) readout."""
    if r is None or r.thought is None:
        return None
    return frozenset(s.get_node(m).content for m in r.thought.members)


def percept_flips(builder, percept_text: str, friction_levels: list) -> tuple:
    """Run a single percept at each swept friction level (in REPLAY, one single-sample trace
    per level), collect the winning node-sets, and decide whether the percept FLIPS (>= 2
    distinct winners across the levels). Returns (flips: bool, n_distinct: int,
    has_winner: bool)."""
    winners = []
    for f in friction_levels:
        s = builder()
        # a replay trace whose FIRST post-baseline read yields exactly friction f:
        #   wall_dt = 1.0, cpu_dt = 1 - f  => compute_friction = f
        # The sensor is PRIMED past its baseline (one throwaway read) so think()'s single
        # per-cycle read sees f, not the neutral baseline (the first ever read primes the
        # baseline and returns neutral — the realistic per-cycle pattern).
        trace = [TelemetrySample(0.0, 0.0), TelemetrySample(1.0, 1.0 - f)]
        sensor = BodySensor(simulated=True, trace=trace)
        sensor.read()  # consume the baseline
        r = think(s, percept_text, body_sensor=sensor)
        winners.append(_winner_set(s, r))
    present = [w for w in winners if w is not None]
    distinct = {w for w in present}
    has_winner = len(present) > 0
    flips = len(distinct) >= 2
    return flips, len(distinct), has_winner


