def test_broadcast_is_the_single_explicit_write_exactly_declared_roads():
    section("§6.2 explicit-write: think(broadcast=True) changes EXACTLY the roads in the "
            "returned Broadcast and NOTHING else (no other road, no node touched)")
    s, n = _small_mind()
    roads_before, nodes_before = _deep_snapshot(s)
    r = think(s, "coffee in the kitchen this morning", broadcast=True)
    roads_after, nodes_after = _deep_snapshot(s)

    check(r.broadcast_ is not None and len(r.broadcast_.road_ids) >= 1,
          "a non-empty Broadcast was produced (the winner had internal roads)")

    # the set of roads whose stored tuple changed must EQUAL the declared broadcast road set
    changed = {rid for rid in roads_after
               if roads_before.get(rid) != roads_after[rid]}
    declared = set(r.broadcast_.road_ids)
    check(changed == declared,
          f"exactly the declared broadcast roads changed (changed={len(changed)} "
          f"declared={len(declared)}; symmetric-diff={len(changed ^ declared)})")

    # NO node was mutated (nodes stay neutral — strengthen() touches no node access stats)
    check(nodes_before == nodes_after,
          "no node access stat moved (the broadcast strengthens roads only; nodes neutral)")

    # the change was a STRENGTHENING (strength went up, never down) on each declared road,
    # and bounded by saturation (<= 1.0)
    ok_up = True
    ok_bound = True
    for rid in declared:
        s_before = roads_before[rid][0]
        s_after = roads_after[rid][0]
        if not (s_after >= s_before):
            ok_up = False
        if not (s_after <= 1.0 + 1e-12):
            ok_bound = False
    check(ok_up, "every broadcast road's strength increased (or held at saturation)")
    check(ok_bound, "every broadcast road's strength stayed <= 1.0 (saturation)")

    # integrity preserved THROUGH the write
    ok_integrity = True
    try:
        s.check_integrity()
    except Exception as e:
        ok_integrity = False
        print("   integrity error:", e)
    check(ok_integrity, "check_integrity() clean after the broadcast write")


def test_broadcast_strengthens_only_internal_roads_not_cross_domain():
    section("§6.2 scope: the broadcast strengthens ONLY roads internal to the winner; the "
            "unperceived domain's roads and the bridge are NOT touched")
    # On _small_mind the winner is the warm domain; the bridge coffee->work and the work
    # domain's internal roads are NOT among the winner's internal roads, so they must NOT move.
    s, n = _small_mind()
    bridge_rid = s.find_road(n["coffee"], n["work"])
    work_internal = [s.find_road(n["work"], n["desk"]),
                     s.find_road(n["work"], n["code"]),
                     s.find_road(n["desk"], n["code"])]
    before = {rid: s.get_road(rid, apply_decay=False).strength
              for rid in [bridge_rid] + work_internal if rid is not None}
    r = think(s, "coffee in the kitchen this morning", broadcast=True)
    declared = set(r.broadcast_.road_ids)
    check(bridge_rid not in declared,
          "the coffee->work bridge is NOT broadcast (it is not internal to the winner)")
    check(not (set(work_internal) & declared),
          "no work-domain internal road is broadcast (the work domain lost / was pruned)")
    after = {rid: s.get_road(rid, apply_decay=False).strength
             for rid in [bridge_rid] + work_internal if rid is not None}
    check(before == after,
          "the bridge and work-domain roads are byte-identical before/after (untouched)")


def test_broadcast_twice_strengthens_same_roads_further_never_others():
    section("§6.2 explicit-write: running broadcast twice strengthens the SAME roads further "
            "(toward saturation), never other roads")
    s, n = _small_mind()
    r1 = think(s, "coffee in the kitchen this morning", broadcast=True)
    set1 = set(r1.broadcast_.road_ids)
    mid = {rid: s.get_road(rid, apply_decay=False).strength for rid in set1}
    r2 = think(s, "coffee in the kitchen this morning", broadcast=True)
    set2 = set(r2.broadcast_.road_ids)
    check(set1 == set2,
          "the second broadcast targets exactly the same internal road set (winner stable)")
    after = {rid: s.get_road(rid, apply_decay=False).strength for rid in set2}
    ok = all(after[rid] >= mid[rid] for rid in set2)
    moved = any(after[rid] > mid[rid] for rid in set2)
    check(ok and moved,
          "the second broadcast strengthened those same roads further (still <= 1.0)")
    check(all(after[rid] <= 1.0 + 1e-12 for rid in set2),
          "still bounded by saturation after the second write")


def test_broadcast_each_internal_road_strengthened_exactly_once():
    section("convergence double-counting guard: each broadcast road is strengthened EXACTLY "
            "ONCE per cycle (traversal_count increments by exactly 1)")
    # This directly falsifies a double-count at a convergence point: even where both directed
    # roads of a pair exist, each distinct road is touched once. Loop-closed on _small_mind.
    s, n = _small_mind()
    r = think(s, "coffee in the kitchen this morning")   # broadcast=False: read the winner
    winner = r.thought
    rids = _internal_road_ids(s, winner)
    tc_before = {rid: s.get_road(rid, apply_decay=False).traversal_count for rid in rids}
    bc = broadcast(s, winner)
    tc_after = {rid: s.get_road(rid, apply_decay=False).traversal_count for rid in rids}
    check(set(bc.road_ids) == set(rids),
          "broadcast targeted exactly the winner's internal roads")
    deltas = {rid: tc_after[rid] - tc_before[rid] for rid in rids}
    check(all(d == 1 for d in deltas.values()),
          f"each internal road's traversal_count incremented by EXACTLY 1 "
          f"(deltas: {sorted(set(deltas.values()))}) — no double counting at convergence")
    # and the road-id list itself contains no duplicates (deduped by RoadID)
    check(len(bc.road_ids) == len(set(bc.road_ids)),
          "the broadcast road-id list has no duplicate RoadID")


