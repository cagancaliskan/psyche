def _det_probe(driver):
    """Run a probe under 6 distinct PYTHONHASHSEED values in fresh interpreters; return the
    list of stdout strings (mirrors the established subprocess-probe determinism pattern)."""
    outs = []
    cwd = os.path.dirname(__file__) or "."
    for seed in ("0", "1", "2", "7", "42", "999"):
        env = dict(os.environ, PYTHONHASHSEED=seed)
        rr = subprocess.run([sys.executable, "-c", driver], cwd=cwd,
                            capture_output=True, text=True, env=env)
        if rr.returncode != 0:
            print("  (subprocess error)\n", rr.stderr)
        outs.append(rr.stdout.strip())
    return outs


def test_determinism_store_state_after_n_broadcast_cycles_across_6_seeds():
    section("§6.4 cross-process determinism: the WHOLE store state after N broadcast cycles "
            "is byte-identical across 6 hash seeds (fresh interpreters); ties everywhere")
    # SPEC-0c §5.1: BIT PATTERNS, never round(x, 9).
    driver = textwrap.dedent('''
        import struct
        def _b(x): return struct.pack("<d", x).hex()
        from psyche_store import SubstrateStore, Clock, NodeType
        from psyche_perceive import think
        s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
        def add(c, t=NodeType.CONCEPT): return s.add_node(c, t)
        coffee=add("coffee",NodeType.ENTITY); warmth=add("warmth",NodeType.SENSATION)
        morning=add("morning routine"); cozy=add("cozy feeling"); kitchen=add("kitchen",NodeType.ENTITY)
        work=add("work"); desk=add("desk",NodeType.ENTITY); deadline=add("deadline pressure"); code=add("writing code")
        def w(a,b,n):
            for _ in range(n): s.traverse(a,b)
        w(coffee,warmth,30); w(coffee,morning,30); w(morning,cozy,30); w(coffee,kitchen,30); w(kitchen,morning,30)
        w(work,desk,30); w(work,deadline,30); w(work,code,30); w(desk,code,30); w(coffee,work,8)
        traces = []
        for _ in range(12):
            r = think(s, "coffee in the kitchen this morning", broadcast=True)
            # the per-cycle broadcast described by STABLE identity (content+seq), never uuid
            bc = tuple(sorted(
                (s.get_node(s.get_road(rid).source_id).content,
                 s.get_node(s.get_road(rid).target_id).content,
                 _b(s.get_road(rid, apply_decay=False).strength))
                for rid in r.broadcast_.road_ids
            ))
            traces.append(bc)
        # the whole store state after all cycles, by stable identity
        rows = []
        for rid in s.all_road_ids():
            rd = s.get_road(rid, apply_decay=False)
            rows.append((s.get_node(rd.source_id).content, s.get_node(rd.target_id).content,
                         rd.creation_seq, _b(rd.strength), rd.traversal_count, rd.closed))
        rows.sort()
        print(repr((tuple(traces), tuple(rows))))
    ''')
    outs = _det_probe(driver)
    check(len(set(outs)) == 1,
          f"store state + broadcast trace identical across 6 hash seeds after 12 broadcast "
          f"cycles (distinct outputs: {len(set(outs))})")


