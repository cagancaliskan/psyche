def _executable_body(func):
    """The source of a function with its leading docstring stripped, so structural checks
    inspect the CODE, not the prose (the docstring legitimately mentions the ceiling/gain in
    order to EXPLAIN that they live in the store, which must not trip a 'no clamp' check)."""
    src = inspect.getsource(func)
    doc = func.__doc__
    if doc:
        # remove the first occurrence of the docstring literal (triple-quoted) wholesale
        for q in ('"""', "'''"):
            start = src.find(q)
            if start != -1:
                end = src.find(q, start + 3)
                if end != -1:
                    return src[:start] + src[end + 3:]
    return src


