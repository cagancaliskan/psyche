# §6.3 NO LOCK-IN — a strong fresh percept still changes the winner (escape)
# ─────────────────────────────────────────────────────────────────────────────

def test_no_lock_in_strong_new_percept_switches_winner():
    section("§6.3 NO LOCK-IN: after biasing winner A over many broadcast cycles, a strong "
            "fresh percept favoring domain B SWITCHES the winner to B (the system escapes)")
    UTT_A = "coffee in the kitchen this morning"
    # B-utterance names work/desk/office. work is created first in B and ties on energy, so
    # it is elected the group representative — and work is a HUB with outgoing roads, so the
    # B spread reaches the whole B domain (a sink representative like "writing code" would
    # spread to nobody; that is a fixture property of directed roads, not a mechanism claim).
    UTT_B = "work at the desk in the office"

    # PRECONDITION 1 (loop-closed): on a fresh store, naming A selects the warm domain A.
    sa, na = _two_domain_mind()
    ra0 = think(sa, UTT_A)
    a_core = {na["coffee"], na["kitchen"], na["morning"]}
    b_core = {na["work"], na["desk"], na["code"]}
    winner_a0 = set(ra0.thought.members) if ra0.thought else set()
    check(a_core <= winner_a0 and not (b_core & winner_a0),
          "PRECONDITION: naming A selects the warm domain A (B's core absent)")

    # PRECONDITION 2 (loop-closed): on a fresh store, naming B selects the work domain B.
    sb, nb = _two_domain_mind()
    rb0 = think(sb, UTT_B)
    winner_b0 = set(rb0.thought.members) if rb0.thought else set()
    check({nb["work"], nb["desk"], nb["code"]} <= winner_b0
          and not ({nb["coffee"], nb["kitchen"], nb["morning"]} & winner_b0),
          "PRECONDITION: naming B selects the work domain B (A's core absent) — B is a real "
          "competitor, so the escape below is non-trivial")

    # Now, on ONE store: bias toward A by broadcasting on the A-utterance for many cycles.
    s, n = _two_domain_mind()
    a_core = {n["coffee"], n["kitchen"], n["morning"]}
    b_core = {n["work"], n["desk"], n["code"]}
    a_kept_winning = True
    for _ in range(40):
        r = think(s, UTT_A, broadcast=True)
        w = set(r.thought.members) if r.thought else set()
        if not (a_core <= w):
            a_kept_winning = False
    check(a_kept_winning,
          "during biasing, A kept winning the A-utterance (there is a real prior winner to "
          "escape from — the test is not vacuous)")

    # ESCAPE: present the strong fresh B percept. Despite 40 cycles of accumulated A-bias, the
    # winner must switch to B. (Direction fixed in advance: a strong new percept overrides
    # accumulated bias.) We run this in BOTH modes to show the escape is a property of
    # selection, not of whether THIS call also writes.
    r_escape = think(s, UTT_B, broadcast=False)
    w_escape = set(r_escape.thought.members) if r_escape.thought else set()
    check(b_core <= w_escape,
          "ESCAPE: the strong fresh B percept switches the winner to domain B")
    check(not (a_core & w_escape),
          "ESCAPE: the prior winner A's core is NOT in the new winner (no lock-in)")
    r_escape2 = think(s, UTT_B, broadcast=True)
    w_escape2 = set(r_escape2.thought.members) if r_escape2.thought else set()
    check(b_core <= w_escape2 and not (a_core & w_escape2),
          "ESCAPE holds in broadcast=True mode too (selection, not the write, decides)")


def test_no_lock_in_escape_then_rebias_to_b_is_stable():
    section("§6.3 NO LOCK-IN (follow-through): after escaping to B, broadcasting on B biases "
            "B without re-locking onto A — the loop tracks the new percept")
    s, n = _two_domain_mind()
    a_core = {n["coffee"], n["kitchen"], n["morning"]}
    b_core = {n["work"], n["desk"], n["code"]}
    # bias A, then switch to B and bias B (UTT_B elects the hub `work` as representative)
    for _ in range(25):
        think(s, "coffee in the kitchen this morning", broadcast=True)
    b_wins_throughout = True
    for _ in range(25):
        r = think(s, "work at the desk in the office", broadcast=True)
        w = set(r.thought.members) if r.thought else set()
        if not (b_core <= w and not (a_core & w)):
            b_wins_throughout = False
    check(b_wins_throughout,
          "after switching, B keeps winning the B-utterance across rebias cycles (the loop "
          "follows the current percept; no relapse to A)")


