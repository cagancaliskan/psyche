# ─────────────────────────────────────────────────────────────────────────────
# §6.3 NO DIVERGENCE — bounded feedback converges toward a finite ceiling
# ─────────────────────────────────────────────────────────────────────────────

def test_no_divergence_broadcast_converges_over_many_cycles():
    section("§6.3 NO DIVERGENCE: over many think(broadcast=True) cycles, road strength stays "
            "<= 1.0 and the broadcast aggregate CONVERGES (per-cycle deltas shrink to ~0), "
            "never grows without limit")
    s, n = _small_mind()
    N = 60
    sums = []          # per-cycle sum of THAT cycle's broadcast road strengths (after)
    road_sets = []     # per-cycle broadcast road-id set
    max_strength_seen = 0.0
    for _ in range(N):
        r = think(s, "coffee in the kitchen this morning", broadcast=True)
        check_bc = r.broadcast_
        road_sets.append(frozenset(check_bc.road_ids))
        sums.append(check_bc.total_strength_after())
        # hard bound: EVERY road in the whole store stays <= 1.0 (global saturation)
        for rid in s.all_road_ids():
            st = s.get_road(rid, apply_decay=False).strength
            if st > max_strength_seen:
                max_strength_seen = st

    # the broadcast targeted the SAME road set every cycle (winner stable), so the per-cycle
    # sums are directly comparable — this also makes the convergence assertion meaningful
    check(len(set(road_sets)) == 1,
          f"the broadcast targeted a stable road set across all {N} cycles "
          f"(distinct sets: {len(set(road_sets))})")
    n_roads = len(road_sets[0])
    check(n_roads >= 1, "the winner had at least one internal road to bias")

    # HARD BOUND: max road strength never exceeded 1.0 (saturation held throughout)
    check(max_strength_seen <= 1.0 + 1e-12,
          f"max road strength stayed <= 1.0 across all cycles (saw {round(max_strength_seen, 9)})")

    # FINITE CEILING: the aggregate is bounded by n_roads * 1.0 and never exceeds it
    check(all(x <= n_roads + 1e-9 for x in sums),
          f"the broadcast aggregate stayed <= the finite ceiling {n_roads} (never exceeded)")

    # CONVERGENCE: the aggregate is non-decreasing and its first-difference shrinks toward 0
    non_decreasing = all(sums[i + 1] >= sums[i] - 1e-12 for i in range(len(sums) - 1))
    check(non_decreasing, "the broadcast aggregate is non-decreasing across cycles")
    deltas = [sums[i + 1] - sums[i] for i in range(len(sums) - 1)]
    # the write is doing real work early (anti-vacuousness): the first delta is positive
    check(deltas[0] > 0.0, "the first cycle's increment is strictly positive (the write acts)")
    # deltas shrink (geometric contraction of strengthen): each no bigger than the previous
    monotone_shrink = all(deltas[i + 1] <= deltas[i] + 1e-12 for i in range(len(deltas) - 1))
    check(monotone_shrink, "successive increments are non-increasing (contraction)")
    # PLATEAU: the last increment is far below the first AND essentially zero — it converged,
    # it did not grow linearly/without limit
    check(deltas[-1] < deltas[0],
          "the final increment is smaller than the first (the aggregate is converging)")
    check(deltas[-1] < 1e-3,
          f"the final increment is ~0 (plateau reached; last delta={deltas[-1]:.2e}) — "
          f"bounded feedback, not unbounded growth")


def test_no_divergence_strengths_strictly_below_one():
    section("§6.3 NO DIVERGENCE (saturation): after many broadcasts a road approaches but "
            "never reaches/exceeds strength 1.0 (the ceiling is approached, not exceeded)")
    s, n = _small_mind()
    for _ in range(80):
        think(s, "coffee in the kitchen this morning", broadcast=True)
    over = [rid for rid in s.all_road_ids()
            if s.get_road(rid, apply_decay=False).strength > 1.0 + 1e-12]
    check(not over, "no road exceeded strength 1.0 after 80 broadcast cycles")
    # at least one broadcast road got CLOSE to the ceiling (the bias is real, saturating)
    warm_internal = s.find_road(n["coffee"], n["warmth"])
    st = s.get_road(warm_internal, apply_decay=False).strength
    check(0.9 < st <= 1.0 + 1e-12,
          f"a heavily-broadcast road approached the saturation ceiling (strength={round(st, 9)})")


