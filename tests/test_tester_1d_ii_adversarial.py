def _dense_clique(s, contents, n=30):
    """A fully-connected (both directions) dense clique of nodes with the given contents,
    each pair worn n times. Returns the list of node ids. The worst case for the single-
    write dedup (every directed pair exists) and for convergence (many internal roads)."""
    ids = [s.add_node(c, NodeType.CONCEPT) for c in contents]
    for i in range(len(ids)):
        for j in range(len(ids)):
            if i != j:
                _worn(s, ids[i], ids[j], n=n)
    return ids


def _deep_snapshot(s):
    """Deep snapshot of ALL stored state: per-road strength/charges/closed/traversal_count/
    last_touched (canonical, decay-free) and per-node access_count/last_accessed. The
    superset a write must change exactly, and a pure read must leave untouched."""
    roads = {}
    for rid in s.all_road_ids():
        r = s.get_road(rid, apply_decay=False)
        roads[rid] = (round(r.strength, 12), tuple(sorted(r.charges.items())),
                      r.closed, r.traversal_count, r.last_touched)
    nodes = {}
    for nid in s.all_node_ids():
        nd = s.get_node(nid)
        nodes[nid] = (nd.access_count, nd.last_accessed)
    return roads, nodes


def _contents(s, ids):
    return sorted(s.get_node(m).content for m in ids)


def _index_snapshot(s):
    """Snapshot the store's adjacency / pair indices by STABLE identity (content+seq), so we
    can prove the write drifts NO index (not just that check_integrity passes)."""
    out = {}
    pair = {}
    for nid in s.all_node_ids():
        c = s.get_node(nid).content, s.get_node(nid).creation_seq
        outs = sorted(
            (s.get_node(s.get_road(r).target_id).content,
             s.get_road(r).creation_seq) for r in s.roads_from(nid)
        )
        out[c] = tuple(outs)
    for rid in s.all_road_ids():
        r = s.get_road(rid, apply_decay=False)
        key = (s.get_node(r.source_id).content, s.get_node(r.target_id).content)
        pair[key] = r.creation_seq
    return out, pair


