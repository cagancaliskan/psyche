def _executable_body(func):
    """Source of a function with its leading docstring removed, so a 'no clamp' audit reads
    the CODE, not prose that legitimately explains where the ceiling lives."""
    src = inspect.getsource(func)
    if func.__doc__:
        for q in ('"""', "'''"):
            start = src.find(q)
            if start != -1:
                end = src.find(q, start + 3)
                if end != -1:
                    return src[:start] + src[end + 3:]
    return src


