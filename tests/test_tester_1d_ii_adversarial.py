def _det_probe(driver_body):
    """Run driver under 6 distinct PYTHONHASHSEED values in fresh interpreters; return the
    list of stdout strings. PYTHONPATH points at src so the subprocess imports resolve from
    its tests/ cwd (our own probe, independent of the builder's)."""
    outs = []
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(os.path.dirname(here), "src")
    for seed in ("0", "1", "2", "7", "42", "999"):
        env = dict(os.environ, PYTHONHASHSEED=seed)
        env["PYTHONPATH"] = src + (os.pathsep + env["PYTHONPATH"]
                                   if env.get("PYTHONPATH") else "")
        rr = subprocess.run([sys.executable, "-c", driver_body],
                            cwd=here, capture_output=True, text=True, env=env)
        if rr.returncode != 0:
            print("  (subprocess error)\n", rr.stderr)
            outs.append("ERROR:" + rr.stderr.strip()[-300:])
        else:
            outs.append(rr.stdout.strip())
    return outs


