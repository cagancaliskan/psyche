def test_B_strengthen_no_charge_is_geometric_contraction_bounded_below_one():
    section("B STRUCTURAL BOUNDEDNESS (analytic): strengthen() with NO charge is the exact "
            "geometric contraction s -> s + g*(1-s), g=0.13 — its fixed point is 1.0, "
            "approached from below and NEVER exceeded. We verify the closed form matches the "
            "store AND that the iterated map provably stays < 1.0 from any start in [0,1).")
    # 1) the store's per-call update equals the closed form s' = s + 0.13*(1-s) with no charge
    s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
    a = s.add_node("a", NodeType.CONCEPT); b = s.add_node("b", NodeType.CONCEPT)
    rid = s.add_road(a, b)
    g = 0.13
    cur = s.get_road(rid, apply_decay=False).strength
    matches = True
    overshoot = False
    for _ in range(300):
        predicted = cur + g * (1.0 - cur)
        s.strengthen(rid)
        actual = s.get_road(rid, apply_decay=False).strength
        if abs(actual - predicted) > 1e-12:
            matches = False
        if actual > 1.0 + 1e-15:
            overshoot = True
        cur = actual
    check(matches,
          "the store's strengthen (no charge) equals the geometric contraction s+0.13*(1-s)")
    check(not overshoot,
          "the iterated contraction never exceeds 1.0 (saturation is structural, not clamped)")
    # 2) iterate the PURE map from many starts in [0,1): it is monotone increasing, bounded
    #    above by 1.0, with strictly shrinking increments -> converges to 1.0 (no divergence)
    bad = None
    for start in (0.0, 0.05, 0.3, 0.5, 0.8, 0.95, 0.999, 0.9999999):
        x = start
        prev_delta = None
        for _ in range(500):
            d = g * (1.0 - x)
            x = x + d
            if x > 1.0 + 1e-12:
                bad = ("overshoot", start, x); break
            if prev_delta is not None and d > prev_delta + 1e-15:
                bad = ("delta grew", start, d, prev_delta); break
            prev_delta = d
        if bad:
            break
    check(bad is None,
          f"the pure contraction map stays < 1.0 with non-increasing increments from every "
          f"start (counterexample: {bad})")


