def test_C_close_competition_bias_does_not_flip_winner_toward_A():
    section("C NO LOCK-IN (close competition, differential): a fixed utterance that names "
            "BOTH domains is decided the SAME way on a heavily-A-biased store as on a FRESH "
            "store — accumulated bias must NOT flip the winner toward A. This is the precise "
            "lock-in failure mode, tested differentially so it cannot false-fail on fixture "
            "quirks (loop-closed)")
    # Mechanism-level, non-circular: we do NOT presuppose which domain SHOULD win a both-named
    # utterance (that depends on clustering/basin resolution we are not grading). The no-lock-in
    # property is purely DIRECTIONAL: biasing A must not corrupt selection so that A wins a
    # percept the un-biased system did not give to A. We compare fresh-store vs A-biased-store.
    UTT_BOTH = "coffee work office desk writing code"   # names A's hub + B's whole region
    a_core = {"coffee", "kitchen", "morning"}

    # winner of the both-named utterance on a FRESH store (the un-biased reference)
    s_fresh, nf = _bridged_two_domain_mind(bridge_dir="b_to_a")
    rf = think(s_fresh, UTT_BOTH)
    wf = frozenset(_contents(s_fresh, rf.thought.members)) if rf.thought else frozenset()

    # winner of the SAME utterance after heavy A-bias on a separate store
    s_bias, nb = _bridged_two_domain_mind(bridge_dir="b_to_a")
    for _ in range(50):
        think(s_bias, "coffee in the kitchen this morning", broadcast=True)
    rb = think(s_bias, UTT_BOTH)
    wb = frozenset(_contents(s_bias, rb.thought.members)) if rb.thought else frozenset()

    # CORE no-lock-in invariant (differential): the winner is identical with/without the bias.
    # If the bias changed the winner, the only direction that is a *defect* is "now contains A's
    # core when it didn't" (lock-in pulls toward the biased domain). We assert the strong form
    # (identical) and, as the decisive guard, that the bias did not ADD A's core.
    fresh_has_A = a_core <= wf
    biased_has_A = a_core <= wb
    check(wb == wf,
          f"the both-named utterance is decided identically with and without heavy A-bias "
          f"(fresh={sorted(wf)} biased={sorted(wb)}) — accumulated bias did not alter selection")
    check(biased_has_A == fresh_has_A,
          "heavy A-bias did NOT flip the winner toward A's core (the decisive lock-in guard: "
          "the biased domain cannot capture a percept it did not already win)")


