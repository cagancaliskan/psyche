def test_A_no_divergence_dense_clique_winner_plateaus():
    section("A NO DIVERGENCE (hostile dense clique): a fully-connected 6-node named clique "
            "(30 internal roads) broadcast for 120 cycles — every road stays <= 1.0 and the "
            "aggregate PLATEAUS (per-cycle delta -> ~0), not unbounded growth (loop-closed)")
    s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
    # a dense clique named by distinct single-token contents so the whole clique is perceived
    ids = _dense_clique(s, ["alfa", "bravo", "charlie", "delta", "echo", "foxtrot"], n=30)
    utt = "alfa bravo charlie delta echo foxtrot"
    N = 120
    sums = []
    road_sets = []
    max_strength = 0.0
    for _ in range(N):
        r = think(s, utt, broadcast=True)
        bc = r.broadcast_
        road_sets.append(frozenset(bc.road_ids))
        sums.append(bc.total_strength_after())
        for rid in s.all_road_ids():
            st = s.get_road(rid, apply_decay=False).strength
            if st > max_strength:
                max_strength = st
    # the winner targeted a STABLE internal-road set (so per-cycle sums are comparable)
    check(len(set(road_sets)) == 1,
          f"the broadcast targeted a stable internal-road set across {N} cycles "
          f"(distinct sets: {len(set(road_sets))})")
    n_roads = len(road_sets[0])
    check(n_roads >= 10, f"the dense clique winner has many internal roads ({n_roads}) — a "
                         f"genuine stress for convergence and dedup")
    # HARD BOUND: nothing ever exceeded 1.0
    check(max_strength <= 1.0 + 1e-12,
          f"max road strength stayed <= 1.0 across all cycles (saw {round(max_strength, 9)})")
    # FINITE CEILING + PLATEAU
    check(all(x <= n_roads + 1e-9 for x in sums),
          f"aggregate stayed <= finite ceiling {n_roads}")
    deltas = [sums[i + 1] - sums[i] for i in range(len(sums) - 1)]
    check(deltas[0] > 0.0, "the write does real work early (first delta strictly positive)")
    check(all(deltas[i + 1] <= deltas[i] + 1e-12 for i in range(len(deltas) - 1)),
          "successive increments are non-increasing (geometric contraction of strengthen)")
    check(deltas[-1] < 1e-3 and deltas[-1] < deltas[0],
          f"PLATEAU: last delta ~0 and << first ({deltas[-1]:.2e} vs {deltas[0]:.2e}) — "
          f"bounded feedback, not unbounded growth")


def test_A_no_divergence_from_near_saturation_does_not_overshoot():
    section("A NO DIVERGENCE (near-saturated start): pre-strengthen the winner's internal "
            "roads to ~0.99, then broadcast 60 cycles — strength approaches but NEVER exceeds "
            "1.0, and increments are tiny throughout (no overshoot past the ceiling)")
    s, n = _small_mind()
    # pre-saturate the warm domain's internal roads to near 1.0 (many manual strengthens),
    # so the broadcast starts in the regime where any additive bug would punch through 1.0.
    p = perceive(s, "coffee in the kitchen this morning")
    clustering = cluster_sources(s, p.sources)
    field_ = build_activation_field(
        s, list(clustering.group_seeds.keys()),
        hop_budget=6, source_energies=clustering.group_seeds,
    )
    coalitions = form_coalitions_from_field(field_, s)
    ws = select_winner(s, coalitions, field_, clustering, p.sources)
    internal = _internal_road_ids(s, ws.winner)
    check(len(internal) >= 1, "precondition: the warm winner has internal roads to saturate")
    for rid in internal:
        for _ in range(60):
            s.strengthen(rid)   # drive each toward the ceiling BEFORE broadcasting
    near = {rid: s.get_road(rid, apply_decay=False).strength for rid in internal}
    check(all(0.95 < v <= 1.0 + 1e-12 for v in near.values()),
          f"precondition: internal roads pre-saturated near 1.0 (min={round(min(near.values()),6)})")
    # now broadcast many cycles from near saturation
    over = False
    last_delta = None
    for _ in range(60):
        before = {rid: s.get_road(rid, apply_decay=False).strength for rid in internal}
        r = think(s, "coffee in the kitchen this morning", broadcast=True)
        after = {rid: s.get_road(rid, apply_decay=False).strength for rid in internal}
        for rid in internal:
            if after[rid] > 1.0 + 1e-12:
                over = True
        last_delta = max(after[rid] - before[rid] for rid in internal)
    check(not over, "no internal road exceeded 1.0 when broadcasting from near saturation")
    check(last_delta is not None and last_delta < 1e-3,
          f"increments are tiny near the ceiling (last max delta={last_delta:.2e}) — the "
          f"approach is asymptotic, never an overshoot")


