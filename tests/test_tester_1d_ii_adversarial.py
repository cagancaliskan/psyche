def test_C_no_lock_in_deeply_biased_winner_still_escapes_bridged_graph():
    section("C NO LOCK-IN (hostile, bridged): after EIGHTY broadcast cycles biasing A on a "
            "graph where B->A is bridged (so a B-percept spreads into the heavily-biased A), "
            "a strong fresh B percept STILL switches the winner to B. Escape is NON-VACUOUS: "
            "A is verified dominant immediately before the switch (loop-closed)")
    UTT_A = "coffee in the kitchen this morning"
    UTT_B = "work at the desk in the office"
    # PRECONDITION (fresh store): naming B selects B (B is a real competitor, escape non-trivial)
    sb, nb = _bridged_two_domain_mind(bridge_dir="b_to_a")
    rb0 = think(sb, UTT_B)
    b_core = {nb["work"], nb["desk"], nb["code"]}
    a_core = {nb["coffee"], nb["kitchen"], nb["morning"]}
    wb0 = set(rb0.thought.members) if rb0.thought else set()
    check(b_core <= wb0, "PRECONDITION: on a fresh store, naming B selects the work domain B")

    # On ONE bridged store: bias A DEEPLY (80 cycles, far past the builder's 40), driving A's
    # internal roads toward saturation — the maximal lock-in pressure this mechanism allows.
    s, n = _bridged_two_domain_mind(bridge_dir="b_to_a")
    a_core = {n["coffee"], n["kitchen"], n["morning"]}
    b_core = {n["work"], n["desk"], n["code"]}
    a_kept_winning = True
    last_a_winner = None
    for _ in range(80):
        r = think(s, UTT_A, broadcast=True)
        w = set(r.thought.members) if r.thought else set()
        last_a_winner = w
        if not (a_core <= w):
            a_kept_winning = False
    check(a_kept_winning,
          "during 80 biasing cycles, A kept winning the A-utterance (a real, deeply-entrenched "
          "prior winner to escape FROM — the escape is not vacuous)")
    # NON-VACUOUSNESS, made concrete: right before the switch, A's internal roads are near
    # saturation (the bias really accumulated) and B's core is NOT in the current A-winner.
    warm_internal = s.find_road(n["coffee"], n["warmth"])
    st = s.get_road(warm_internal, apply_decay=False).strength
    check(st > 0.9,
          f"A's internal conductance is deeply entrenched right before the switch "
          f"(coffee->warmth strength={round(st,6)} > 0.9)")
    check(last_a_winner is not None and not (b_core <= last_a_winner),
          "immediately before the switch, B's core was NOT the winner (A genuinely dominant)")

    # ESCAPE: present the strong fresh B percept. Despite 80 cycles of A-bias AND a B->A bridge
    # that routes B's spread into the biased A region, the winner MUST switch to B.
    r_escape = think(s, UTT_B, broadcast=False)
    w_escape = set(r_escape.thought.members) if r_escape.thought else set()
    check(b_core <= w_escape,
          "ESCAPE: the strong fresh B percept switches the winner to domain B (no lock-in, "
          "even with a bridge into the heavily-biased domain)")
    check(not (a_core & w_escape),
          "ESCAPE: A's core is excluded from the new winner (B's basin won outright)")
    # and the escape is a property of SELECTION, not of whether this call also writes
    r_escape2 = think(s, UTT_B, broadcast=True)
    w_escape2 = set(r_escape2.thought.members) if r_escape2.thought else set()
    check(b_core <= w_escape2 and not (a_core & w_escape2),
          "ESCAPE holds in broadcast=True mode too (the write does not re-lock onto A)")


