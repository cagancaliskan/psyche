def test_over_swallow_flips_through_live_think():
    section("§6.1 ACCEPTANCE (loop-closed): the winning thought excludes the bridged, "
            "unperceived work/code domain")
    s, n = _small_mind()
    # coalitions are SYSTEM-GENERATED by think() -> form_coalitions_from_field; nothing
    # here is hand-built. The input names only the warm domain.
    r = think(s, "coffee in the kitchen this morning")
    check(r.workspace is not None and r.thought is not None,
          "think() produced a workspace result and a winner")
    winner = set(r.thought.members)
    check(n["work"] not in winner and n["code"] not in winner,
          "the winner contains NEITHER work NOR code (over-swallow flipped)")
    check(n["desk"] not in winner and n["deadline"] not in winner,
          "the rest of the unperceived work domain (desk, deadline) is excluded too")
    check({n["work"], n["code"], n["desk"], n["deadline"]} <= set(r.workspace.pruned_members),
          "the whole unperceived work domain is recorded in pruned_members")
    # the warm group the input named is PRESERVED in the winner
    check({n["coffee"], n["kitchen"], n["morning"]} <= winner,
          "the perceived warm domain is preserved in the winner (not over-pruned)")


def test_over_swallow_flip_generalizes_second_graph():
    section("§6.1 anti-circularity: the flip GENERALIZES on a second, independently-built "
            "isomorphic-but-relabelled graph (not tuned to coffee/work)")
    # Same TOPOLOGY, different content + creation order, different utterance. A strong
    # bridge (n=8) into an UNNAMED domain must still be pruned.
    s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
    # build the unnamed "project" domain FIRST (different creation order than _small_mind)
    job = s.add_node("project", NodeType.CONCEPT)
    table = s.add_node("table surface", NodeType.ENTITY)
    due = s.add_node("due date", NodeType.CONCEPT)
    prog = s.add_node("programming task", NodeType.CONCEPT)
    # the named "tea" domain
    tea = s.add_node("tea", NodeType.ENTITY)
    heat = s.add_node("heat", NodeType.SENSATION)
    dawn = s.add_node("dawn ritual", NodeType.CONCEPT)
    snug = s.add_node("snug mood", NodeType.CONCEPT)
    galley = s.add_node("galley", NodeType.ENTITY)
    _worn(s, tea, heat); _worn(s, tea, dawn); _worn(s, dawn, snug)
    _worn(s, tea, galley); _worn(s, galley, dawn)
    _worn(s, job, table); _worn(s, job, due); _worn(s, job, prog); _worn(s, table, prog)
    _worn(s, tea, job, n=8)   # the strong bridge into the UNNAMED project domain
    r = think(s, "tea in the galley at dawn")
    check(r.thought is not None, "winner exists on the isomorphic graph")
    winner = set(r.thought.members)
    check(job not in winner and prog not in winner and table not in winner and due not in winner,
          "the unnamed project domain (job/prog/table/due) is pruned on the second graph")
    check({tea, galley, dawn} <= winner,
          "the named tea domain is preserved on the second graph")


