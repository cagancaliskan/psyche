def test_density_competition_prefers_tight_over_sprawling():
    section("A2 competition: a tight intensely-active coalition beats a larger sprawling "
            "one of equal total activation (density, not summed strength)")
    # NARROW UNIT TEST of the pure helper (hand-built coalitions allowed here only — NOT in
    # the acceptance path). Two coalitions with equal total activation (6.0) but different
    # size: density must pick the tighter (smaller) one. This proves the rule is density,
    # not the old summed-strength tiebreak, and that competition genuinely discriminates.
    s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
    ids = [s.add_node(f"x{i}", NodeType.CONCEPT) for i in range(9)]
    seqm = {nid: s.get_node(nid).creation_seq for nid in ids}
    # tight: 3 members, total 6.0  -> density 6/ max(3,guard)
    tight_members = {ids[0]: 2.0, ids[1]: 2.0, ids[2]: 2.0}
    tight = Coalition(members=tight_members, strength=6.0,
                      _seq={k: seqm[k] for k in tight_members})
    # sprawling: 6 members, total 6.0 -> density 6/ max(6,guard)
    sprawl_members = {ids[3]: 1.0, ids[4]: 1.0, ids[5]: 1.0,
                      ids[6]: 1.0, ids[7]: 1.0, ids[8]: 1.0}
    sprawl = Coalition(members=sprawl_members, strength=6.0,
                       _seq={k: seqm[k] for k in sprawl_members})
    ranked = rank_coalitions([sprawl, tight])  # deliberately worst-first input order
    check(ranked[0] is tight,
          "the tighter, denser coalition wins the competition over the sprawling one")
    # and the legacy summed-strength rule would have TIED them (both 6.0) — so the density
    # rule is doing real work here, not riding the old key.
    check(tight.strength == sprawl.strength,
          "the two coalitions have equal SUMMED strength (so density is the deciding key)")


