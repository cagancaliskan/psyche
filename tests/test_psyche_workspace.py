def _scale_coalition(c, k):
    """Return a copy of a coalition with every member activation and the strength scaled by
    k (creation_seq / breakthrough marks unchanged). Used to test the SELECTION layer's
    scale-invariance in isolation from the upstream absolute activation floors."""
    members = {m: a * k for m, a in c.members.items()}
    return Coalition(
        members=members, strength=c.strength * k, intrusive=c.intrusive,
        breakthrough_members=set(c.breakthrough_members), _seq=dict(c._seq),
    )


def test_selection_layer_scale_invariance_isolated():
    section("scale-invariance (selection layer, isolated): scaling coalition activations by "
            "ANY positive constant keeps the winner + pruning")
    # This isolates 1d-i's OWN criteria from the upstream absolute floors. The competition
    # is a ratio (density = strength/size) and pruning reads ROAD STRENGTH (independent of
    # activation), so BOTH are scale-invariant in activation magnitude. We build the field +
    # coalitions ONCE, then feed scaled COPIES of the coalitions to select_winner.
    s, n = _small_mind()
