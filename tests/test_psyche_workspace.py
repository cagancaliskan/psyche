def test_anti_overcorrection_perceived_domain_survives():
    section("anti-overcorrection: when the input NAMES the work domain, work/desk/code are "
            "NOT pruned (a perceived domain always survives)")
    s, n = _small_mind()
    # the input now names the work domain
    r = think(s, "work at the desk")
    perceived = set(r.perception.sources)
    check({n["work"], n["desk"]} <= perceived,
          "precondition: perception named work and desk")
    winner = set(r.thought.members) if r.thought else set()
    # work and desk are perceived seeds; deadline/code are in their (now perceived) domain
    check(n["work"] in winner and n["desk"] in winner,
          "the perceived work/desk survive (never pruned)")
    check(r.workspace is not None and
          n["work"] not in r.workspace.pruned_members and
          n["desk"] not in r.workspace.pruned_members,
          "no perceived member is in pruned_members")
    # the watershed keeps the rest of the perceived domain too (loosely-attached members of
    # a NAMED domain are not stranded)
    code_or_deadline_in = (n["code"] in winner) or (n["deadline"] in winner)
    check(code_or_deadline_in,
          "members of the perceived work domain (code/deadline) are kept with it")
    # and the winner is non-empty (pruning did not wipe everything out)
    check(len(winner) >= 2, "the winner is non-empty (pruning did not over-correct)")


def test_pruning_never_empties_the_winner():
    section("safety: pruning never empties the winner (asserted-negative for over-pruning)")
    # Through the live loop, on the over-swallow case, the winner must still be non-empty
