def test_KNOWN_LIMITATION_unnamed_domain_bridged_ge_cohesion_is_kept():
    section("KNOWN LIMITATION (asserted-negative): 1d-i pruning is a parameter-free "
            "cohesion-valley / relative-attachment watershed, NOT pure domain-membership. "
            "An UNNAMED domain bridged into the named region AT LEAST AS STRONGLY AS its "
            "own internal cohesion has NO valley and is therefore KEPT — over-swallow "
            "RECURS in that topology. Accepted design (2026-06-20); the divergence is "
            "always SAFE (a perceived member is never pruned).")
    # This is the builder-owned record of the limitation the tester's adversarial suite
    # (T12c/d/e/f) documents independently. It is loop-closed through the real
    # perceive -> cluster -> field -> coalitions -> select_winner pipeline (coalitions are
    # SYSTEM-GENERATED, never hand-built) on an INDEPENDENTLY-built graph (lake/gadget, not
    # the tester's tea/gizmo). The limitation is STRUCTURAL: it is created by making the
    # bridge >= internal cohesion via traversal COUNTS, never by tuning any threshold (1d-i
    # has no calibrated pruning constant to tune).
    s = SubstrateStore(clock=Clock(simulated=True, start=0.0))
    # named domain: lake/shore/ripple — tight (n=30) so it is the basin core / wins.
    lake = s.add_node("lake", NodeType.ENTITY)
    shore = s.add_node("shore", NodeType.ENTITY)
    ripple = s.add_node("ripple pattern", NodeType.CONCEPT)
    _worn(s, lake, shore, n=30); _worn(s, lake, ripple, n=30); _worn(s, shore, ripple, n=30)
    # UNNAMED community: gadget/sensor, internal cohesion n=12, bridged from lake at n=14
    # (bridge STRICTLY STRONGER than internal cohesion -> no cohesion valley at the seam).
    gadget = s.add_node("gadget device", NodeType.CONCEPT)
    sensor = s.add_node("sensor unit", NodeType.CONCEPT)
    _worn(s, gadget, sensor, n=12)     # the unnamed community's internal cohesion
    _worn(s, lake, gadget, n=14)       # the bridge into it, >= internal cohesion

    # The structural precondition is READ FROM THE GRAPH (not encoded into the assertion):
    # the bridge to the named region is >= the unnamed community's internal cohesion.
    bridge = _strongest_road_strength(s, gadget, lake)
    internal = _strongest_road_strength(s, gadget, sensor)
    check(bridge >= internal,
          f"precondition (read from graph, not assumed): gadget's bridge to the named "
          f"region {round(bridge, 4)} >= its internal cohesion {round(internal, 4)} "
          f"(no cohesion valley at the seam)")

    # (a) The WATERSHED MECHANISM itself (the rule this limitation is about) KEEPS the
    #     unnamed community. This is floor-independent and load-bearing: a pure
    #     domain-membership C1 would PRUNE gadget/sensor (no source named their domain); the
    #     cohesion-valley watershed does NOT, because there is no valley. The KEEP verdict is
    #     computed by the real watershed, never hand-placed.
    perceived = {lake, shore, ripple}
    members = [lake, shore, ripple, gadget, sensor]
    kept = _perceived_domain_members(s, members, perceived)
    check(gadget in kept and sensor in kept,
          "DIVERGENCE FROM MEMBERSHIP: the unnamed gadget/sensor community is KEPT by the "
          "cohesion-valley watershed (bridge >= internal cohesion -> no valley), where pure "
          "domain-membership would have pruned it")

    # (b) Loop-closed through the real selection: name only the lake domain, let the system
    #     build the field + coalitions, and select. We assert the divergence is observable on
    #     the real selection path WHEN the field reaches the unnamed community (guarded on
    #     raw-winner membership so floor behavior cannot make this flaky — the same honest
    #     conditional the tester uses): if gadget/sensor are in the raw winner, they are NOT
    #     pruned and survive into the winner (over-swallow recurs here).
    p = perceive(s, "lake shore ripple")
    check(perceived <= set(p.sources) and gadget not in p.sources and sensor not in p.sources,
          "precondition: perception named the lake domain only (gadget/sensor unnamed)")
    clustering = cluster_sources(s, p.sources)
    field_ = build_activation_field(
        s, list(clustering.group_seeds.keys()),
        hop_budget=6, source_energies=clustering.group_seeds,
    )
    coalitions = form_coalitions_from_field(field_, s)   # SYSTEM-GENERATED, not hand-built
    ws = select_winner(s, coalitions, field_, clustering, p.sources)
    raw = set(ws.raw_winner.members) if ws.raw_winner else set()
    winner = set(ws.winner.members) if ws.winner else set()
    if {gadget, sensor} & raw:
        check(not ({gadget, sensor} & set(ws.pruned_members)) and {gadget, sensor} & winner,
              "DOCUMENTED over-swallow RECURRENCE on the real selection path: the unnamed "
              "community is KEPT (not pruned) when its bridge >= its internal cohesion")
    else:
        # If the upstream floors kept the unnamed community out of the raw winner via this
        # field, the divergence is not observable through this path; (a) above is the
        # decisive, floor-independent evidence for the limitation.
        check(True,
              "(unnamed community not in the raw winner via this field; the watershed-level "
              "evidence in (a) is the decisive, floor-independent record of the limitation)")

    # (c) Anti-overcorrection re-asserted IN THIS adversarial regime: the divergence is in
    #     the SAFE direction — a PERCEIVED member is never pruned even here.
    check(perceived <= kept,
          "SAFE DIRECTION: no perceived member is pruned in the bridge>=cohesion regime "
          "(the limitation is over-INCLUSION of an unnamed domain, never over-EXCLUSION)")


