"""
Test suite for Psyche workspace selection — step 1d-i (competition + over-swallow pruning).

WHAT 1d-i IS (and is NOT) — the discipline this suite enforces:
  - MECHANISM, NOT MEANING. These tests verify the selection is correct, deterministic,
    pure, integrity-preserving, and scale-invariant. They make NO cognitive claim: the
    winner is a SELECTED INFORMATION STRUCTURE, never "what the system is conscious/aware
    of." Meaning is the validator's job at 1e against external data, never asserted here.
  - PURE SELECTION. 1d-i mutates NOTHING. select_winner / think(broadcast=False) must
    leave the store byte-identical (deep snapshot: strengths, charges, closure, traversal
    counts, AND node access stats). The broadcast/feedback WRITE is 1d-ii; this suite
    asserts only that 1d-i selection is pure and that the default broadcast=False path
    writes nothing. (1d-ii's broadcast write, its boundedness, and the explicit-write
    purity nuance are verified in test_psyche_workspace_broadcast.py. The 1d-i asserted-
    negative that broadcast was 'not built yet' has been FLIPPED to the built behavior,
    exactly as 1d-i flipped 1c's over-swallow asserted-negatives — see
    test_broadcast_true_now_performs_the_single_write below.)
  - LOOP-CLOSED. The over-swallow flip and the anti-overcorrection control are driven
    through the real think() on real utterances; coalitions are SYSTEM-GENERATED by
    form_coalitions_from_field. Hand-built coalitions are confined to narrow unit tests of
    pure helpers and never used as the basis for an over-swallow / competition claim.
  - ANTI-CIRCULARITY. The flip is not tuned to one case: it is shown to generalize on a
    SECOND, independently-built graph (isomorphic-but-relabelled), and the
    anti-overcorrection control proves the rule is not "prune everything far from a seed."

Run directly:
    python3 test_psyche_workspace.py
"""

