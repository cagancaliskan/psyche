  function setupHeader() {
    head = doc.querySelector('.k-head');
    if (!head) { head = el('header', { 'class': 'k-head' }); doc.body.insertBefore(head, doc.body.firstChild); }
    head.innerHTML = P.headerHTML();
    var lastY = scrollY;
    // Hidden means moved out of view only: never inert, so Tab still reaches it from anywhere,
    // and the moment focus enters it, it shows.
    function setHidden(h) {
      if (h === headHidden) return;
      if (h && (head.contains(doc.activeElement) || (menu && menu.open))) return;
      headHidden = h; head.classList.toggle('is-hidden', h);
    }
    var scrolled = scrollY > 8;
    head.classList.toggle('is-scrolled', scrolled);
    onScroll({
      read: function () { return scrollY; },
      write: function (y) {
        if ((y > 8) !== scrolled) { scrolled = y > 8; head.classList.toggle('is-scrolled', scrolled); }
        if (y > lastY + 6 && y > 120) setHidden(true);
        else if (y < lastY - 6 || y < 60) setHidden(false);
        lastY = y;
      }
    });
    head.addEventListener('focusin', showHeader);
  }

  /* ------------------------------------------------------------------ */
  /* Phone menu: one full-screen list, the same four links and the theme   */
  /* ------------------------------------------------------------------ */
  var menu = null;
  function buildMenu() {
    var node = el('div', { 'class': 'k-menu', id: 'k-menu', role: 'dialog', 'aria-modal': 'true', 'aria-label': 'Menu', hidden: '' });
    node.innerHTML =
      '<div class="k-menu__top"><a class="k-head__home" href="' + HOME + '" aria-label="Psyche, home">' + wordmark() + '</a>' +
      '<div class="k-menu__ctl">' + themeButton('k-ti--menu') + '<button type="button" class="k-ctl" data-k-close>Close</button></div></div>' +
      '<nav class="k-menu__list" aria-label="Site">' + navLinks('k-menu__link') + '</nav>';
    doc.body.appendChild(node);
    node.querySelector('[data-k-close]').addEventListener('click', function () { closeMenu(true); });
    node.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') { e.preventDefault(); closeMenu(true); return; }
      if (e.key !== 'Tab') return;
      var f = Array.prototype.filter.call(node.querySelectorAll('a[href], button'), function (x) { return x.offsetParent !== null; });
      if (!f.length) return;
      var first = f[0], lastEl = f[f.length - 1];
      if (e.shiftKey && (doc.activeElement === first || !node.contains(doc.activeElement))) { e.preventDefault(); lastEl.focus(); }
      else if (!e.shiftKey && doc.activeElement === lastEl) { e.preventDefault(); first.focus(); }
    });
    menu = { node: node, open: false, returnTo: null };
    syncThemeControls();
  }
  function openMenu() {
    if (!menu) buildMenu();
    if (menu.open) return;
    menu.open = true; menu.returnTo = doc.activeElement;
    Array.prototype.forEach.call(doc.body.children, function (c) {
      if (c === menu.node || c.tagName === 'SCRIPT' || c.classList.contains('k-orb-veil')) return;
      c.setAttribute('inert', ''); c.setAttribute('data-k-inert', '');
    });
    doc.body.classList.add('k-menu-open');
    doc.querySelectorAll('[data-k-menu]').forEach(function (b) { b.setAttribute('aria-expanded', 'true'); });
    menu.node.hidden = false;
    requestAnimationFrame(function () { menu.node.classList.add('is-open'); });
    var first = menu.node.querySelector('.k-menu__link');
    (first || menu.node.querySelector('[data-k-close]')).focus();
  }
  function closeMenu(restore) {
    if (!menu || !menu.open) return;
    menu.open = false;
    doc.querySelectorAll('[data-k-inert]').forEach(function (c) { c.removeAttribute('inert'); c.removeAttribute('data-k-inert'); });
    doc.body.classList.remove('k-menu-open');
    doc.querySelectorAll('[data-k-menu]').forEach(function (b) { b.setAttribute('aria-expanded', 'false'); });
    menu.node.classList.remove('is-open');
    var hide = function () { if (!menu.open) menu.node.hidden = true; };
    if (reduced()) hide(); else setTimeout(hide, 240);
    showHeader();
    if (restore !== false && menu.returnTo && menu.returnTo.focus) menu.returnTo.focus();
  }
  P.menu = { open: openMenu, close: closeMenu, isOpen: function () { return !!(menu && menu.open); } };
  // a phone turned to a wide screen: the links are in the header again
  window.addEventListener('resize', function () { if (menu && menu.open && innerWidth > 700) closeMenu(false); });

  /* ------------------------------------------------------------------ */
  /* Big sentences: word-by-word light as they are scrolled through        */
  /* ------------------------------------------------------------------ */
  function setupBig() {
    var items = [];
    doc.querySelectorAll('.k-big').forEach(function (sec) {
      var line = sec.querySelector('.k-big__line'); if (!line || line.getAttribute('data-k-split')) return;
      line.setAttribute('data-k-split', '1');
      var src = line.querySelector('.k-big__source');
      if (src) src.remove();
      var text = line.textContent.replace(/\s+/g, ' ').trim();
      var words = text.split(' ');
      line.innerHTML = '<span class="k-vh">' + esc(text) + '</span><span aria-hidden="true">' +
        words.map(function (w) { return '<span class="k-w">' + esc(w) + '</span>'; }).join(' ') + '</span>';
      if (src) line.appendChild(src);
      var spans = Array.prototype.slice.call(line.querySelectorAll('.k-w'));
      items.push({ sec: sec, spans: spans, last: spans.map(function () { return ''; }), p: -1 });
    });
    if (!items.length) return;
    onScroll({
      // read: where each sentence's section is (one layout read for all of them)
      read: function () {
        var vh = innerHeight;
        return items.map(function (it) {
          var r = it.sec.getBoundingClientRect(), span = Math.max(1, r.height - vh);
          return reduced() ? 1 : clamp((-r.top + vh * 0.15) / span, 0, 1);
        });
      },
      // write: only the words whose light changed
      write: function (ps) {
        items.forEach(function (it, k) {
          var p = ps[k]; if (p === it.p) return; it.p = p;
          var n = it.spans.length;
          for (var i = 0; i < n; i++) {
            var a = n > 1 ? (i / (n - 1)) * 0.8 : 0, b = Math.min(1, a + 0.2);
            var o = (p <= a ? 0.15 : p >= b ? 1 : 0.15 + 0.85 * (p - a) / (b - a)).toFixed(3);
            if (it.last[i] !== o) { it.spans[i].style.opacity = o; it.last[i] = o; }
          }
        });
      }
    });
  }

  /* ------------------------------------------------------------------ */
  /* Parts rail                                                           */
  /* ------------------------------------------------------------------ */
  function slug(s) { return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''); }
  function setupRail() {
    var parts = Array.prototype.slice.call(doc.querySelectorAll('[data-k-part]'));
    if (!parts.length) parts = Array.prototype.slice.call(doc.querySelectorAll('[data-k-parts] h2'));
    if (!parts.length || doc.body.hasAttribute('data-k-no-rail')) return;
    var nav = el('nav', { 'class': 'k-rail is-off', 'aria-label': 'Parts of this page' });
    var ol = el('ol');
    function go(p, e) {
      e.preventDefault();
      var y = p.getBoundingClientRect().top + scrollY - 88;
      window.scrollTo({ top: y, behavior: reduced() ? 'auto' : 'smooth' });
      history.replaceState(null, '', '#' + p.id);
      setTimeout(function () { p.setAttribute('tabindex', '-1'); p.focus({ preventScroll: true }); }, reduced() ? 0 : 500);
    }
    var names = parts.map(function (p) {
      var name = p.getAttribute('data-k-part') || p.textContent.trim();
      if (!p.id) p.id = slug(name);
      return name;
    });
    var marks = parts.map(function (p, i) {
      var li = el('li'), a = el('a', { href: '#' + p.id });
      a.innerHTML = '<span class="k-rail__name">' + esc(names[i]) + '</span>';
      a.addEventListener('click', function (e) { go(p, e); });
      li.appendChild(a); ol.appendChild(li);
      return a;
    });
    nav.appendChild(ol);
    // On a phone the rail is hidden (CSS, under 701 px) and the parts are a plain list at the top of
    // the text: inside [data-k-parts-here] if the page has one, else at the start of the first .k-read.
    var spot = doc.querySelector('[data-k-parts-here]'), firstRead = doc.querySelector('.k-read');
    if (spot || firstRead) {
      var list = el('nav', { 'class': 'k-parts', 'aria-label': 'Parts of this page' }), lol = el('ol');
      parts.forEach(function (p, i) {
        var li = el('li'), a = el('a', { href: '#' + p.id });
        a.textContent = names[i];
        a.addEventListener('click', function (e) { go(p, e); });
        li.appendChild(a); lol.appendChild(li);
      });
      list.appendChild(lol);
      if (spot) spot.appendChild(list); else firstRead.insertBefore(list, firstRead.firstChild);
    }
    var head = doc.querySelector('.k-head');
    (head && head.nextSibling) ? doc.body.insertBefore(nav, head.nextSibling) : doc.body.appendChild(nav);
    // the things the rail steps aside for (anything wider than the column) and the footer, found once
    var wides = Array.prototype.slice.call(doc.querySelectorAll('.k-big, .k-figure--wide, .k-figure--bleed, [data-k-wide]'));
    var end = doc.querySelector('.k-foot'), cur0 = -2, hide0 = null;
    onScroll({
      read: function () {
        var vh = innerHeight, line = vh * 0.4, cur = -1, top0 = 0, y = scrollY, i, r;
        for (i = 0; i < parts.length; i++) { r = parts[i].getBoundingClientRect(); if (r.top <= line) cur = i; if (i === 0) top0 = r.top; }
        var off = y < Math.min(top0 + y - vh * 0.9, vh * 0.6);
        var past = !!end && end.getBoundingClientRect().top < vh * 0.5;
        // step aside for anything that runs wider than the column (big sentences, wide figures)
        var wide = false;
        for (i = 0; i < wides.length && !wide; i++) { r = wides[i].getBoundingClientRect(); wide = r.top < vh * 0.75 && r.bottom > vh * 0.25; }
        return { cur: cur, hide: off || past || wide };
      },
      write: function (o) {
        if (o.cur !== cur0) {
          marks.forEach(function (a, i) { if (i === o.cur) a.setAttribute('aria-current', 'true'); else a.removeAttribute('aria-current'); });
          cur0 = o.cur;
        }
        if (o.hide !== hide0) {
          hide0 = o.hide;
          nav.classList.toggle('is-off', o.hide);
          if (o.hide) nav.setAttribute('inert', ''); else nav.removeAttribute('inert');
        }
      }
    });
  }

