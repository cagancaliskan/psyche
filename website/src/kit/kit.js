  function afterFonts() {
    figures.forEach(function (r) {
      if (r.mounted && !r.fontsAtBuild && r.def.modelFor) { r.fontsAtBuild = true; idle(function () { refreshModel(r, false); }); }
    });
  }
  whenStyled(function () { try { if (doc.fonts && doc.fonts.ready) doc.fonts.ready.then(afterFonts); } catch (e) { /* none */ } });
