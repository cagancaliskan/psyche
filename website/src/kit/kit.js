  /* The orb: a particle sphere in the landing's look, on a 2D canvas      */
  /* ------------------------------------------------------------------ */
  // The idea of a particle orb shown while a page loads follows "Thinking Orb" by adrielzimbril
  // (21st.dev); its drawing code was not obtained and nothing of it is copied. Drawn in the film's
  // particle look: a Fibonacci sphere of soft points, white with mint and periwinkle, turning.
  function mulberry(a) { return function () { a |= 0; a = a + 0x6D2B79F5 | 0; var t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; }; }
  P.mulberry = mulberry;
  function orbPoints(n) {
    var rng = mulberry(7), pts = [], ga = Math.PI * (3 - Math.sqrt(5));
    for (var k = 0; k < n; k++) {
      var y = 1 - (k / (n - 1)) * 2, r = Math.sqrt(1 - y * y), th = ga * k;
      var inner = rng() < 0.16, rr = inner ? 0.35 + 0.5 * rng() : 1 + (rng() - 0.5) * 0.03;
      var u = rng();
      pts.push({ x: Math.cos(th) * r * rr, y: y * rr, z: Math.sin(th) * r * rr, c: u < 0.26 ? 1 : u < 0.4 ? 2 : 0,
        s: inner ? 0.7 : 0.8 + rng() * 0.7, sx: rng() * 2 - 1, sy: rng() * 2 - 1, d: rng() * 0.35 });
    }
    return pts;
  }
  var ORB_COL = {
    dark: [[238, 241, 248], [94, 240, 200], [138, 162, 255]],
    light: [[10, 13, 20], [8, 122, 92], [47, 79, 214]]
  };
  // the colours as fill strings, made once (each point's light is set with globalAlpha)
  var ORB_FILL = {};
  Object.keys(ORB_COL).forEach(function (k) { ORB_FILL[k] = ORB_COL[k].map(function (c) { return 'rgb(' + c.join(',') + ')'; }); });
  // spread: 0 = the sphere, 1 = scattered across the screen. scan: 0..1 strength of the scan band.
  function drawOrb(ctx, W, H, cx, cy, R, t, pts, o) {
    var theme = P.theme.get(), fills = ORB_FILL[theme], dpr = o.dpr || 1, lastC = -1;
    ctx.globalCompositeOperation = theme === 'dark' ? 'lighter' : 'source-over';
    var a = t * (o.speed || 0.35), ca = Math.cos(a), sa = Math.sin(a), tilt = 0.38, ct = Math.cos(tilt), st = Math.sin(tilt);
    var band = Math.sin(t * 2.2) * 0.9;
    for (var i = 0; i < pts.length; i++) {
      var p = pts[i];
      var x = p.x * ca + p.z * sa, z = -p.x * sa + p.z * ca, y = p.y * ct - z * st; z = p.y * st + z * ct;
      var k = 3 / (3 - z), px = cx + x * R * k, py = cy + y * R * k;
      var sp = o.spread ? clamp((o.spread - p.d) / (1 - p.d), 0, 1) : 0;
      if (sp > 0) { var e = sp * sp * (3 - 2 * sp); px += (cx + p.sx * W * 0.62 - px) * e; py += (cy + p.sy * H * 0.62 - py) * e; }
      var depth = (z + 1) / 2, al = (0.22 + 0.78 * depth) * (o.alpha == null ? 1 : o.alpha) * (1 - sp * 0.6);
      if (o.scan) { var dd = Math.abs(y - band); if (dd < 0.18) al = Math.min(1, al + o.scan * (0.18 - dd) * 5); }
      if (theme === 'light') al = Math.min(1, al * 1.15);
      if (al < 0.004) continue;
      var rad = Math.max(0.6, p.s * (R / 90) * dpr * (0.75 + 0.5 * depth));
      if (p.c !== lastC) { ctx.fillStyle = fills[p.c]; lastC = p.c; }
      ctx.globalAlpha = al > 1 ? 1 : al;
      ctx.beginPath(); ctx.arc(px, py, rad, 0, 6.2832); ctx.fill();
    }
    ctx.globalAlpha = 1;
    ctx.globalCompositeOperation = 'source-over';
  }
  // Mount a small orb on a canvas. Returns { turn(ms), still(), destroy() }.
  P.orb = function (canvas, opts) {
    opts = opts || {};
    var ctx = canvas.getContext('2d'), pts = orbPoints(opts.points || 240), raf = 0, until = 0, t = opts.t || 1.3, last = 0;
    function size() {
      var dpr = Math.min(2, window.devicePixelRatio || 1), r = canvas.getBoundingClientRect();
      canvas.width = Math.max(1, Math.round(r.width * dpr)); canvas.height = Math.max(1, Math.round(r.height * dpr));
      return dpr;
    }
    var dpr = size();
    function paint(scan) {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      drawOrb(ctx, canvas.width, canvas.height, canvas.width / 2, canvas.height / 2, canvas.width * 0.4, t, pts, { dpr: dpr * 0.5, scan: scan, speed: 0.9 });
    }
    function frame(ts) {
      var dt = last ? Math.min(0.05, (ts - last) / 1000) : 0; last = ts; t += dt;
      paint(1);
      if (ts < until) raf = requestAnimationFrame(frame); else { raf = 0; last = 0; paint(0); if (opts.onSettle) opts.onSettle(); }
    }
    paint(0);
    P.theme.onChange(function () { paint(0); });
    return {
      turn: function (ms) {
        if (reduced()) { paint(0); if (opts.onSettle) setTimeout(opts.onSettle, ms || 900); return; }
        until = now() + (ms || 900); if (!raf) raf = requestAnimationFrame(frame);
      },
      resize: function () { dpr = size(); paint(0); },
      still: function () { until = 0; },
      destroy: function () { cancelAnimationFrame(raf); }
    };
  };

