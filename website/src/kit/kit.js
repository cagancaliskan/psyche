  function buildSvg(rec) {
    var def = rec.def, model = rec.model, v = viewOf(def, model), pal = palNow();
    var id = def.id + '-live';
    var fit = rec.host.getAttribute('data-fit') || 'xMidYMid meet';
    var glow = !!pal.glow, fg = glow && def.frontGlow !== false;
    var vb = 'xmlns="' + SVGNS + '" viewBox="0 0 ' + v.w + ' ' + v.h + '"';
    var html =
      '<svg class="k-layer k-layer-back" ' + vb + ' aria-hidden="true" focusable="false">' +
        (glow ? '<defs>' + backGlow(id + '-bglow', v) + '</defs>' : '') +
        '<g id="' + id + '-b"' + (glow ? ' filter="url(#' + id + '-bglow)"' : '') + '></g></svg>' +
      '<svg class="k-layer k-layer-front" ' + vb + ' role="img" aria-labelledby="' + id + '-t" aria-describedby="' + id + '-d">' +
        '<title id="' + id + '-t">' + esc(def.title) + '</title><desc id="' + id + '-d"></desc>' +
        (fg ? '<defs>' + frontGlow(id + '-fglow', v) + '</defs>' : '') +
        '<g id="' + id + '-f"' + (fg ? ' filter="url(#' + id + '-fglow)"' : '') + '></g><g id="' + id + '-l"></g><g id="' + id + '-k" aria-hidden="true"></g></svg>';
    var old = rec.layers || [];
    rec.art.insertAdjacentHTML('beforeend', html);
    old.forEach(function (n) { n.remove(); });
    var svgs = rec.art.querySelectorAll(':scope > svg.k-layer');
    rec.layers = [svgs[svgs.length - 2], svgs[svgs.length - 1]];
    rec.layers.forEach(function (s) { s.setAttribute('preserveAspectRatio', fit); });
    rec.svg = rec.layers[1];
    rec.backSvg = rec.layers[0];
    rec.g = { back: doc.getElementById(id + '-b'), front: doc.getElementById(id + '-f'), labels: doc.getElementById(id + '-l'), mark: doc.getElementById(id + '-k') };
    rec.descEl = doc.getElementById(id + '-d');
    rec.last = {}; rec.lastMark = null; rec.lastDesc = null; rec.parts = null; rec.partLast = null; rec.drawn = false;
    render(rec);
  }
  // Writes a layer only when its text changed.
  function writeLayer(rec, k, text) {
    if (rec.last[k] === text) return;
    rec.g[k].innerHTML = text; rec.last[k] = text;
    if (perf.on) perf.bytes += text.length;
  }
  // The front: one text, or parts (an array, or an object of named parts). Each part is its own <g>,
  // rewritten only when its text changed; parts keep the order in which they first appeared, and a
  // part missing from a later frame is emptied.
  function writeFront(rec, f) {
    var g = rec.g.front;
    if (f == null || typeof f === 'string') {
      if (rec.parts) { g.textContent = ''; rec.parts = null; rec.partLast = null; rec.last.front = null; }
      writeLayer(rec, 'front', f || '');
      return;
    }
    if (!rec.parts) { g.textContent = ''; rec.parts = {}; rec.partLast = {}; rec.last.front = null; }
    var seen = {}, k, txt, p;
    for (k in f) {
      if (!Object.prototype.hasOwnProperty.call(f, k)) continue;
      seen[k] = 1; txt = f[k] || '';
      p = rec.parts[k];
      if (!p) { p = doc.createElementNS(SVGNS, 'g'); p.setAttribute('data-k-part', k); g.appendChild(p); rec.parts[k] = p; rec.partLast[k] = ''; }
      if (rec.partLast[k] !== txt) { p.innerHTML = txt; rec.partLast[k] = txt; if (perf.on) perf.bytes += txt.length; }
    }
    for (k in rec.parts) if (!seen[k] && rec.partLast[k] !== '') { rec.parts[k].textContent = ''; rec.partLast[k] = ''; }
  }
  function render(rec) {
    var pal = palNow(), def = rec.def, t0 = perf.on ? now() : 0;
    var done = false;
    // incremental path: after one full draw, a figure with update() changes the existing elements itself
    if (def.update && rec.drawn) {
      var ctx = { svg: rec.svg, front: rec.g.front, labels: rec.g.labels, parts: rec.parts, pal: pal, view: viewOf(def, rec.model) };
      if (def.update(rec.model, rec.state, ctx) !== false) {
        done = true;
        // the DOM no longer matches the last text written: the next full draw rewrites everything
        rec.last.front = null; rec.last.labels = null;
        if (rec.partLast) for (var k in rec.partLast) rec.partLast[k] = null;
        if (perf.on) perf.updates++;
      }
    }
    if (!done) {
      var L = layersOf(def.draw(rec.model, rec.state, pal));
      writeLayer(rec, 'back', L.back);
      writeFront(rec, L.front);
      writeLayer(rec, 'labels', L.labels);
      rec.drawn = true;
    }
    if (!rec.running) describeNow(rec);
    drawFocusMark(rec, pal);
    syncControls(rec);
    if (perf.on) { perf.renders++; perf.ms += now() - t0; }
  }
  function describeNow(rec) {
    if (!rec.def.describe || !rec.descEl) return;
    var d = rec.def.describe(rec.model, rec.state);
    if (d !== rec.lastDesc) { rec.descEl.textContent = d; rec.lastDesc = d; }
  }
  // Keyboard focus on a figure: a quiet ring around its handle (def.handle(model, state) -> [x, y]
  // in view units), never a ring around the whole figure. Without a handle, CSS draws a short
  // mark under the figure's lower left corner instead.
  function drawFocusMark(rec, pal) {
    var g = rec.g && rec.g.mark; if (!g) return;
    var out = '';
    if (rec.focused && rec.def.handle) {
      var h = rec.def.handle(rec.model, rec.state);
      if (h && h.length) {
        var v = viewOf(rec.def, rec.model), r = Math.max(11, Math.min(22, Math.max(v.w, v.h) * 0.011));
        var r2 = pal.name === 'dark' ? 'mint' : 'peri';
        out = S.circle(h[0], h[1], r, pal, r2, 1.4) + S.circle(h[0], h[1], r + 4, pal, r2, 0.8, 0.45);
      }
    }
    if (rec.lastMark !== out) { g.innerHTML = out; rec.lastMark = out; }
  }
  function setState(rec, s, byUser) {
    rec.state = s;
    if (rec.def.settled) rec.settled = !!rec.def.settled(rec.model, s);
    render(rec);
    if (byUser && rec.def.describe) announce(rec.def.describe(rec.model, s));
  }

  /* -- One frame loop for the whole page -------------------------------- */
  // Every playing figure and the scroll effects share one requestAnimationFrame callback: scroll
  // effects first (all layout read, then all writes), then each figure. A figure is in the loop at
  // most once. def.fps caps a figure's frame rate (default 60, so a 120 Hz screen does not double the
  // work; slow motion may ask for 30 or less). Nothing runs while the tab is hidden or the page is leaving.
  var playing = [], rafId = 0, scrollDirty = false, scrollers = [], leaving = false;
  function want() { if (!rafId) rafId = requestAnimationFrame(frameAll); }
  // Scroll effects (header, big sentences, rail) register { read(), write(r) }: once per frame every
  // read runs first (layout is measured once), then every write.
  function onScroll(s) { scrollers.push(s); scrollDirty = true; want(); }
  function runScroll() {
    scrollDirty = false;
    var r = scrollers.map(function (s) { return s.read(); });
    scrollers.forEach(function (s, i) { s.write(r[i]); });
  }
  function scrollNeeded() { if (!scrollers.length) return; scrollDirty = true; want(); }
  window.addEventListener('scroll', scrollNeeded, { passive: true });
  window.addEventListener('resize', scrollNeeded);
  if (rmq.addEventListener) rmq.addEventListener('change', scrollNeeded);
  function frameAll() {
    rafId = 0;
    if (scrollDirty) runScroll();
    if (!leaving) {
      var t = now();
      playing.slice().forEach(function (rec) { if (rec.running) frameOf(rec, t); });
    }
    if (playing.length && !leaving) want();
  }
  function frameOf(rec, t) {
    var def = rec.def, fps = def.fps == null ? 60 : def.fps;
    var ms = t - rec.lastT;
    if (fps > 0) { var iv = 1000 / fps; if (ms < iv - Math.min(4, iv * 0.25)) return; }
    rec.lastT = t;
    var dt = Math.min(0.1, ms / 1000), s = rec.state, q = rec.seq;
    try {
      if (q && q.status === 'playing') {
        s = seqFrame(rec, s, dt);
        rec.state = s;
        if (q.status === 'done') seqDone(rec);
      } else {
        s = ownMotion(rec, s, dt);
        rec.state = s;
        if (def.settled && def.settled(rec.model, s)) { rec.settled = true; dropLoop(rec); }
      }
      render(rec);
    } catch (e) { dropLoop(rec); syncControls(rec); setTimeout(function () { throw e; }, 0); } // the other figures keep playing
    if (!rec.running) syncControls(rec);
  }
  function dropLoop(rec) {
    rec.running = false;
    var i = playing.indexOf(rec); if (i >= 0) playing.splice(i, 1);
  }
  function startLoop(rec) {
    if (rec.running || leaving) return;
    rec.running = true; rec.lastT = now(); rec.acc = 0;
    if (playing.indexOf(rec) < 0) playing.push(rec);
    want();
    syncControls(rec);
  }
  function stopLoop(rec) {
    if (!rec.running) return;
    dropLoop(rec);
    if (leaving) return;
    // the drawing already shows this state: only the description and the controls change
    describeNow(rec);
    syncControls(rec);
  }
  function stopAll() { playing.slice().forEach(function (r) { r.hiddenStop = true; stopLoop(r); }); }
  doc.addEventListener('visibilitychange', function () {
    if (doc.hidden) stopAll();
    else resumeAll();
  });
  // a figure stopped because the tab was hidden or the page was leaving goes on where it was
  function resumeAll() {
    figures.forEach(function (r) {
      if (!r.hiddenStop) return;
      r.hiddenStop = false;
      if (r.mounted && r.visible && !r.settled && !r.userPaused && !reduced() && !leaving && !doc.hidden) startLoop(r);
    });
  }
  // the figure's own motion for dt seconds: tick, or step at `rate` a second
  function ownMotion(rec, s, dt) {
    var def = rec.def;
    if (def.tick) return def.tick(rec.model, s, dt);
    if (def.step) { rec.acc += dt * (def.rate || 6); while (rec.acc >= 1) { rec.acc -= 1; s = def.step(rec.model, s); } }
    return s;
  }

  /* -- Sequences: a figure that tells its whole story by itself ---------- */
  // def.sequence is a list of steps (or { steps, then }). Each step lasts `dur` ms and may:
  //   do(model, state) -> state         once, when the step begins (place a wall, fire a cell);
  //   to: { field: value } or (model, state) -> { field: value }
  //                                     numeric fields of the state eased from where they are to these
  //                                     values over the step (`ease`: 'inOut' (default), 'in', 'out',
  //                                     'travel', 'settle', 'pass', 'linear', or a function of 0..1);
  //   frame(model, state, u) -> state   every frame, u the eased progress 0..1;
  //   tick: false                       hold the figure's own tick or step during it (they run by default).
  // The kit plays it from initialState when the figure is well in view (60% of it, or of the screen)
  // after the page has opened, lets it rest on its last picture, plays it again when the figure comes
  // back after having been out of view, and stops it at once when the reader acts on the figure.
  // stillState must be the picture the sequence ends on: it is the still and the reduced-motion state.
  var EASE = {
    linear: function (u) { return u; },
    'in': function (u) { return u * u * u; },
    out: function (u) { return 1 - Math.pow(1 - u, 3); },
    inOut: function (u) { return u < 0.5 ? 4 * u * u * u : 1 - Math.pow(-2 * u + 2, 3) / 2; },
    // travel: from rest to rest, the way a pushed thing or a hand moves. x = 1 - (1-u)^3 (1+3u),
    // speed 12u(1-u)^2: zero at both ends, peak 16/9 of the average at a third of the step, then a
    // long slowing over the last two thirds. Never passes 1.
    travel: function (u) { return 1 - Math.pow(1 - u, 3) * (1 + 3 * u); },
    // settle: an arrival at a value, from rest, quicker to start and longer to settle. x = 1 - (1-u)^4 (1+4u),
    // speed 20u(1-u)^3: zero at both ends, peak 135/64 (about 2.1) of the average at a quarter of the
    // step. Never passes 1 (no overshoot, safe for anything that encodes a number).
    settle: function (u) { return 1 - Math.pow(1 - u, 4) * (1 + 4 * u); },
    // pass: one move from rest to rest past a row of marks, a flat middle so evenly spaced marks go by
    // at an even beat. Over the first 27% of the time it gathers speed (peak about 2.6 times the later
    // pace at 15%) and eases back to a steady pace, reached at 43% of the way; it holds that pace to 85%
    // of the way, then slows to rest over the last 30% of the time (smoothstep ramps). Speed is
    // continuous and zero at both ends; never passes 1.
    pass: (function () {
      var xa = 0.27, pa = 0.43, pb = 0.85;
      var xb = ((pb - pa) + 2 * (1 - pb) * xa) / ((pb - pa) + 2 * (1 - pb)), vc = (pb - pa) / (xb - xa), h = (pa / xa - vc / 2) * 15 / 8;
      return function (u) {
        if (u <= 0) return 0; if (u >= 1) return 1;
        if (u < xa) { var y = u / xa, y3 = y * y * y; return xa * (vc * (y3 - y3 * y / 2) + 16 * h * (y3 / 3 - y3 * y / 2 + y3 * y * y / 5)); }
        if (u < xb) return pa + (u - xa) * vc;
        var z = (u - xb) / (1 - xb); return pb + (1 - xb) * vc * (z - z * z * z + z * z * z * z / 2);
      };
    })()
  };
  P.ease = EASE; // the same curves, by name, for a figure whose model eases something the sequence cannot reach
  function seqOf(def) {
    var sq = def.sequence, steps = Array.isArray(sq) ? sq : (sq.steps || []);
    if (!steps.length) throw new Error('Psyche.figure "' + def.id + '": sequence has no steps');
    return { steps: steps, then: sq.then || 'rest', status: 'idle', i: 0, t: 0, begun: false, to: null, from: null };
  }
  function seqFrame(rec, s, dt) {
    var q = rec.seq, m = rec.model, left = dt * 1000, step = q.steps[q.i];
    if (step.tick !== false) s = ownMotion(rec, s, dt);
    while (q.status === 'playing') {
      step = q.steps[q.i];
      var dur = step.dur || 0;
      if (!q.begun) {
        q.begun = true; q.t = 0;
        if (step['do']) s = step['do'](m, s);
        q.to = step.to ? (typeof step.to === 'function' ? step.to(m, s) : step.to) : null;
        q.from = {};
        if (q.to) for (var k in q.to) q.from[k] = s[k];
      }
      var use = Math.min(Math.max(0, dur - q.t), left);
      q.t += use; left -= use;
      var u = dur ? clamp(q.t / dur, 0, 1) : 1, e = (typeof step.ease === 'function' ? step.ease : (EASE[step.ease] || EASE.inOut))(u);
      if (q.to) {
        var n = {}; for (var a in s) n[a] = s[a];
        for (var b in q.to) n[b] = q.from[b] + (q.to[b] - q.from[b]) * e;
        s = n;
      }
      if (step.frame) s = step.frame(m, s, e);
      if (q.t < dur) break;
      q.i++; q.begun = false;
      if (q.i >= q.steps.length) { q.status = 'done'; break; }
      if (left <= 0) break;
    }
    return s;
  }
  function startSeq(rec) {
    var q = rec.seq;
    if (!q || leaving) return;
    if (reduced()) { q.status = 'done'; setState(rec, stillStateOf(rec.def, rec.model), true); return; }
    q.i = 0; q.begun = false; q.status = 'playing';
    rec.userPaused = false; rec.settled = false;
    stopLoop(rec);
    rec.state = rec.def.initialState(rec.model);
    render(rec);
    startLoop(rec);
  }
  function seqDone(rec) {
    var q = rec.seq;
    if (q.then === 'play' && rec.auto && !(rec.def.settled && rec.def.settled(rec.model, rec.state))) return; // the figure's own motion goes on
    rec.settled = true; dropLoop(rec);
  }
  // the reader acted on the figure: the sequence stops where it is and the figure is theirs
  function yieldSeq(rec) {
    var q = rec.seq;
    if (!q || q.status === 'yielded' || q.status === 'idle' && !rec.mounted) return;
    if (q.status === 'playing') stopLoop(rec);
    q.status = 'yielded';
    rec.settled = false;
    maybeAutoplay(rec); // the figure's own motion (if it has any) goes on for the reader
    syncControls(rec);
  }
  // fully out of view: next time it comes into view, it plays again from the start
  function seqOut(rec) {
    var q = rec.seq;
    if (!q || reduced() || q.status === 'idle') return;
    q.status = 'idle'; q.i = 0; q.begun = false;
    rec.userPaused = false; rec.settled = false;
    rec.state = rec.def.initialState(rec.model);
    render(rec);
  }
  function replay(rec) { if (rec.seq) startSeq(rec); else { rec.settled = true; play(rec); } }

  function play(rec) {
    var def = rec.def;
    if (rec.seq) {
      if (rec.seq.status === 'paused' && !reduced()) { rec.seq.status = 'playing'; rec.userPaused = false; startLoop(rec); }
      else startSeq(rec);
      return;
    }
    rec.userPaused = false;
    if (rec.settled) { rec.state = def.initialState(rec.model); rec.settled = false; }
    if (reduced()) { // no motion: show where the motion would end
      rec.state = stillStateOf(def, rec.model); rec.settled = true; render(rec);
      if (def.describe) announce(def.describe(rec.model, rec.state));
      return;
    }
    startLoop(rec);
  }
